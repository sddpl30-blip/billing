#!/usr/bin/env node
/**
 * Generates the Prisma baseline, and verifies it.
 *
 * The baseline is `server/migrations/*.sql` concatenated in order, plus the
 * rows the SQL runner would have recorded. That last part matters: with them,
 * a database baselined through Prisma is also consistent with
 * `node server/migrate.mjs`, so the two tools agree about what is applied
 * instead of each insisting the schema has not been created.
 *
 * Generating it is the easy half. The half worth having is the check: the
 * baseline is applied to an empty database, the migration runner is applied to
 * another, and the two schemas are dumped and compared. A baseline that drifts
 * from the migrations is worse than none, because `prisma migrate resolve`
 * would then record a lie.
 *
 *   node scripts/build-prisma-baseline.mjs             # generate
 *   node scripts/build-prisma-baseline.mjs --verify    # generate and compare
 *
 * Verifying needs a PostgreSQL it may create and drop two databases on, named
 * by ADMIN_URL (or DIRECT_URL, or DATABASE_URL — the database in it is only
 * used to issue CREATE DATABASE).
 */

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'server', 'migrations');
const outDir = join(root, 'prisma', 'migrations', '0_init');
const outFile = join(outDir, 'migration.sql');

const checksum = (text) => createHash('sha256').update(text, 'utf8').digest('hex').slice(0, 16);

const files = readdirSync(migrationsDir)
  .filter(name => name.endsWith('.sql'))
  .sort()
  .map(name => {
    const text = readFileSync(join(migrationsDir, name), 'utf8');
    return { name, text, checksum: checksum(text) };
  });

const header = `-- Prisma baseline for an existing SocietyBooks database.
--
-- GENERATED by scripts/build-prisma-baseline.mjs from server/migrations/*.sql.
-- Do not edit: run that script instead, with --verify, which applies this file
-- to an empty database and diffs the result against a database the migration
-- runner built. The two match, or the script fails.
--
-- WHAT IT IS NOT: a migration to run by hand, and not a licence to use
-- \`prisma migrate dev\`. Prisma cannot express the deferred constraint
-- triggers that make an unbalanced journal entry impossible to commit, the
-- trigger that refuses a posting into a closed period, the control-party rule,
-- the DO INSTEAD NOTHING delete rules, or the partial unique indexes. A schema
-- Prisma created from its own schema file would be missing every one of them,
-- which is why the SQL migrations remain the migration path.
--
-- AGAINST A DATABASE THAT ALREADY HAS THE SCHEMA:
--
--   npx prisma migrate resolve --applied 0_init
--
-- records this as applied without executing it, so \`prisma migrate status\` is
-- clean. Then \`prisma db pull\` to refresh prisma/schema.prisma from the
-- database, and \`prisma generate\` for the typed client.
--
-- AGAINST AN EMPTY DATABASE: prefer \`node server/migrate.mjs\`. It records each
-- file with its checksum and refuses to continue if one that was already
-- applied has since changed. This file ends by recording the same rows, so a
-- database created from it is consistent with the runner too.
--
-- Covers: ${files.map(f => f.name).join(', ')}

`;

const body = files
  .map(f => `-- ${'='.repeat(68)}\n-- ${f.name}\n-- ${'='.repeat(68)}\n\n${f.text}\n`)
  .join('\n');

const footer = `
-- ${'='.repeat(68)}
-- The runner's own record, so both migration tools agree about this database.
-- ${'='.repeat(68)}

INSERT INTO schema_migrations (version, checksum) VALUES
${files.map(f => `  ('${f.name}', '${f.checksum}')`).join(',\n')}
ON CONFLICT (version) DO NOTHING;
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, header + body + footer);
console.log(`wrote prisma/migrations/0_init/migration.sql (${files.length} migrations)`);

if (!process.argv.includes('--verify')) {
  console.log('Not verified. Re-run with --verify against a PostgreSQL to compare schemas.');
  process.exit(0);
}

// --- verification ----------------------------------------------------------

const adminUrl = process.env.ADMIN_URL ?? process.env.DIRECT_URL ?? process.env.DATABASE_URL;
if (adminUrl === undefined || adminUrl === '') {
  console.error(
    'Verification needs a database URL in ADMIN_URL, DIRECT_URL or DATABASE_URL. It creates\n' +
    'and drops two scratch databases, so the role needs CREATEDB.',
  );
  process.exit(2);
}

/** Replaces the database name in a URL, keeping every parameter. */
function withDatabase(url, name) {
  const parsed = new URL(url);
  parsed.pathname = `/${name}`;
  return parsed.toString();
}

function psql(url, args) {
  const result = spawnSync('psql', [url, '--no-psqlrc', '--quiet', '--set', 'ON_ERROR_STOP=1', ...args], {
    encoding: 'utf8', shell: false,
  });
  return { ok: result.status === 0, out: ((result.stdout ?? '') + (result.stderr ?? '')).trim() };
}

function dump(url) {
  const result = spawnSync('pg_dump', ['--schema-only', '--no-owner', '--no-acl', url], {
    encoding: 'utf8', shell: false, maxBuffer: 64 * 1024 * 1024,
  });
  if (result.status !== 0) throw new Error(`pg_dump failed: ${result.stderr}`);
  return (result.stdout ?? '')
    .split('\n')
    // Comments, blank lines and psql's own \restrict tokens — which are
    // random per dump — are not schema.
    .filter(line => line.trim() !== '' && !line.startsWith('--')
      && !line.startsWith('\\restrict') && !line.startsWith('\\unrestrict'))
    .join('\n');
}

const stamp = Date.now().toString(36);
const fromBaseline = `sb_verify_baseline_${stamp}`;
const fromRunner = `sb_verify_runner_${stamp}`;

const admin = (sql) => psql(adminUrl, ['--command', sql]);
let failed = false;

try {
  for (const name of [fromBaseline, fromRunner]) {
    const created = admin(`CREATE DATABASE ${name}`);
    if (!created.ok) throw new Error(`could not create ${name}: ${created.out}`);
  }

  const applied = psql(withDatabase(adminUrl, fromBaseline), ['--file', outFile]);
  if (!applied.ok) throw new Error(`the baseline would not apply: ${applied.out}`);

  const runner = spawnSync(process.execPath, [join(root, 'server', 'migrate.mjs')], {
    encoding: 'utf8',
    shell: false,
    env: { ...process.env, DIRECT_URL: withDatabase(adminUrl, fromRunner), DATABASE_URL: '' },
  });
  if ((runner.status ?? 1) !== 0) {
    throw new Error(`the migration runner failed: ${runner.stdout}${runner.stderr}`);
  }

  const baselineSchema = dump(withDatabase(adminUrl, fromBaseline));
  const runnerSchema = dump(withDatabase(adminUrl, fromRunner));

  if (baselineSchema === runnerSchema) {
    console.log('verified: the baseline produces the same schema as the migrations');
  } else {
    failed = true;
    const left = baselineSchema.split('\n');
    const right = runnerSchema.split('\n');
    console.error('MISMATCH between the baseline and the migrations:');
    for (let i = 0; i < Math.max(left.length, right.length); i++) {
      if (left[i] !== right[i]) {
        console.error(`  line ${i + 1}`);
        console.error(`    baseline:   ${left[i] ?? '(end)'}`);
        console.error(`    migrations: ${right[i] ?? '(end)'}`);
        break;
      }
    }
  }

  // Both tools should consider the baselined database fully migrated.
  const status = spawnSync(process.execPath, [join(root, 'server', 'migrate.mjs'), 'status'], {
    encoding: 'utf8',
    shell: false,
    env: { ...process.env, DIRECT_URL: withDatabase(adminUrl, fromBaseline), DATABASE_URL: '' },
  });
  const pending = (status.stdout ?? '').split('\n').filter(line => line.startsWith('PENDING'));
  if (pending.length > 0) {
    failed = true;
    console.error(
      'the runner still considers migrations pending on the baselined database:\n  ' +
      pending.join('\n  '),
    );
  } else {
    console.log('verified: the migration runner sees the baselined database as fully applied');
  }
} finally {
  for (const name of [fromBaseline, fromRunner]) {
    admin(`DROP DATABASE IF EXISTS ${name}`);
  }
}

process.exit(failed ? 1 : 0);
